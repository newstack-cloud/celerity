package build

import (
	"os"
	"path/filepath"
)

// LambdaPythonBootstrap is the Lambda-specific HandlerBootstrap for Python.
// It wraps the developer's app in the Celerity Python SDK's AWS Lambda
// adapter (celerity.serverless.aws.create_lambda_handler).
type LambdaPythonBootstrap struct{}

// lambdaPythonAdapterDistribution is the distribution providing the
// celerity.serverless.aws module the generated entry file imports.
//
// The bare distribution is enough. The SDK wheel ships the whole celerity
// package tree, the adapter included, and the adapter imports nothing beyond
// the standard library and its own siblings, so no optional extra gates it.
// Unlike Node, where the adapter is a separate package the project has to
// depend on explicitly.
const lambdaPythonAdapterDistribution = "celerity-sdk"

// RequiredPackage returns the distribution the generated entry file imports from.
func (p *LambdaPythonBootstrap) RequiredPackage() string {
	return lambdaPythonAdapterDistribution
}

const (
	lambdaPythonBootstrapFilename = "__celerity_lambda_entry__.py"
	lambdaPythonBootstrapHandler  = "__celerity_lambda_entry__.handler"
)

const lambdaPythonBootstrapContent = `"""Auto-generated by Celerity CLI. Do not edit."""
from celerity.serverless.aws import create_lambda_handler

handler = create_lambda_handler()
`

// Generate respects an existing entry file in stagingDir so developers
// can opt out of the generated bootstrap by writing their own.
func (p *LambdaPythonBootstrap) Generate(stagingDir string) (string, error) {
	target := filepath.Join(stagingDir, lambdaPythonBootstrapFilename)
	if _, err := os.Stat(target); err == nil {
		return lambdaPythonBootstrapHandler, nil
	}
	if err := os.WriteFile(target, []byte(lambdaPythonBootstrapContent), 0644); err != nil {
		return "", err
	}
	return lambdaPythonBootstrapHandler, nil
}
