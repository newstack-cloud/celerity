package sqlschema

import (
	"fmt"
	"strings"
)

// CodegenLanguage is a target language for `schema codegen`.
type CodegenLanguage string

const (
	LangTypeScript CodegenLanguage = "typescript"
	LangPython     CodegenLanguage = "python"
)

// GeneratedFile is a single codegen output: the file name (relative to the
// output directory) and its contents.
type GeneratedFile struct {
	Name    string
	Content string
}

// GenerateCode renders type-safe code for a parsed schema in the given language.
// resourceName names the output file and is used only for the header. v0 supports
// TypeScript (row interfaces + column/table constants) and Python (Pydantic
// models). There is no ORM coupling.
func GenerateCode(s *Schema, lang CodegenLanguage, resourceName string) (*GeneratedFile, error) {
	switch lang {
	case LangTypeScript:
		return &GeneratedFile{
			Name:    kebabCase(resourceName) + ".ts",
			Content: generateTypeScript(s, resourceName),
		}, nil
	case LangPython:
		return &GeneratedFile{
			Name:    snakeCase(resourceName) + ".py",
			Content: generatePython(s, resourceName),
		}, nil
	default:
		return nil, fmt.Errorf("unsupported codegen language %q (supported: typescript, python)", lang)
	}
}

func generateTypeScript(s *Schema, resourceName string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s.ts is auto-generated by `celerity schema codegen`, so do not edit it.\n", kebabCase(resourceName))
	b.WriteString("// Field names mirror the database columns exactly (what your driver returns for a\n")
	b.WriteString("// plain query); only type names are stylised. Map to camelCase in your own layer\n")
	b.WriteString("// if you want it, because codegen keeps the shape faithful to the database.\n\n")

	tables := sortedKeys(s.Tables)
	for _, name := range tables {
		table := s.Tables[name]
		fmt.Fprintf(&b, "/** %s */\n", tableComment(name, table))
		fmt.Fprintf(&b, "export type %s = {\n", entityTypeName(name, table))
		for _, colName := range orderedColumns(table) {
			col := table.Columns[colName]
			tsType := tsType(col.Type)
			if col.Nullable && !col.PrimaryKey {
				tsType += " | null"
			}
			if col.Description != "" {
				fmt.Fprintf(&b, "  /** %s */\n", col.Description)
			}
			fmt.Fprintf(&b, "  %s: %s;\n", colName, tsType)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("export const Tables = {\n")
	for _, name := range tables {
		fmt.Fprintf(&b, "  %s: %q,\n", name, name)
	}
	b.WriteString("} as const;\n")

	for _, name := range tables {
		fmt.Fprintf(&b, "\nexport const %sColumns = {\n", entityTypeName(name, s.Tables[name]))
		for _, colName := range orderedColumns(s.Tables[name]) {
			fmt.Fprintf(&b, "  %s: %q,\n", colName, colName)
		}
		b.WriteString("} as const;\n")
	}

	return b.String()
}

func generatePython(s *Schema, resourceName string) string {
	tables := sortedKeys(s.Tables)

	// Determine which imports the generated models need.
	needDatetime, needAny, needOptional := false, false, false
	for _, name := range tables {
		for _, col := range s.Tables[name].Columns {
			switch pyType(col.Type) {
			case "datetime":
				needDatetime = true
			case "Any":
				needAny = true
			}
			if col.Nullable && !col.PrimaryKey {
				needOptional = true
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s.py is auto-generated by `celerity schema codegen`, so do not edit it.\n", snakeCase(resourceName))
	b.WriteString("# Field names mirror the database columns exactly (what your driver returns for a\n")
	b.WriteString("# plain query); only class names are stylised.\n")
	b.WriteString("from pydantic import BaseModel\n")
	if needDatetime {
		b.WriteString("from datetime import datetime\n")
	}
	typingImports := []string{}
	if needAny {
		typingImports = append(typingImports, "Any")
	}
	if needOptional {
		typingImports = append(typingImports, "Optional")
	}
	if len(typingImports) > 0 {
		fmt.Fprintf(&b, "from typing import %s\n", strings.Join(typingImports, ", "))
	}

	for _, name := range tables {
		table := s.Tables[name]
		fmt.Fprintf(&b, "\n\nclass %s(BaseModel):\n", entityTypeName(name, table))
		cols := orderedColumns(table)
		if len(cols) == 0 {
			b.WriteString("    pass\n")
			continue
		}
		for _, colName := range cols {
			col := table.Columns[colName]
			pt := pyType(col.Type)
			if col.Nullable && !col.PrimaryKey {
				pt = fmt.Sprintf("Optional[%s]", pt)
			}
			fmt.Fprintf(&b, "    %s: %s\n", colName, pt)
		}
	}

	return b.String()
}

func tableComment(name string, t Table) string {
	if t.Description != "" {
		return t.Description
	}
	return fmt.Sprintf("A row from the %q table", name)
}

// Primary keys come first, then the rest, each group sorted alphabetically. The
// order has to be deterministic for codegen output to be stable, which the
// freshness check depends on.
func orderedColumns(t Table) []string {
	var pk, rest []string
	for _, name := range sortedKeys(t.Columns) {
		if t.Columns[name].PrimaryKey {
			pk = append(pk, name)
		} else {
			rest = append(rest, name)
		}
	}
	return append(pk, rest...)
}

// bigint and the exact numerics map to string to avoid JavaScript number
// precision loss.
func tsType(sqlType string) string {
	switch baseSQLType(sqlType) {
	case "bigint", "int8", "bigserial", "serial8", "numeric", "decimal", "money":
		return "string"
	case "smallint", "int2", "integer", "int", "int4", "serial", "serial4",
		"real", "float4", "double precision", "float8":
		return "number"
	case "boolean", "bool":
		return "boolean"
	case "timestamp", "timestamptz", "timestamp with time zone",
		"timestamp without time zone", "date", "time", "timetz":
		return "Date"
	case "json", "jsonb":
		return "unknown"
	case "bytea":
		return "string"
	case "uuid", "text", "varchar", "character varying", "char", "character",
		"citext", "inet", "cidr", "macaddr":
		return "string"
	default:
		return "unknown"
	}
}

func pyType(sqlType string) string {
	switch baseSQLType(sqlType) {
	case "bigint", "int8", "bigserial", "serial8", "numeric", "decimal", "money":
		return "str"
	case "smallint", "int2", "integer", "int", "int4", "serial", "serial4":
		return "int"
	case "real", "float4", "double precision", "float8":
		return "float"
	case "boolean", "bool":
		return "bool"
	case "timestamp", "timestamptz", "timestamp with time zone",
		"timestamp without time zone", "date", "time", "timetz":
		return "datetime"
	case "json", "jsonb":
		return "Any"
	case "bytea":
		return "bytes"
	case "uuid", "text", "varchar", "character varying", "char", "character",
		"citext", "inet", "cidr", "macaddr":
		return "str"
	default:
		return "Any"
	}
}

// Lowercases a type and strips any length or precision modifier, so
// "VARCHAR(255)" and "numeric(10,2)" reduce to "varchar" and "numeric".
func baseSQLType(sqlType string) string {
	t := strings.ToLower(strings.TrimSpace(sqlType))
	if i := strings.IndexByte(t, '('); i >= 0 {
		t = strings.TrimSpace(t[:i])
	}
	// Arrays and other suffixes are treated by their base name.
	t = strings.TrimSuffix(t, "[]")
	return strings.TrimSpace(t)
}

// The generated type name is the author's typeName override verbatim, or failing
// that the table name singularised and PascalCased, so that "customers" becomes
// "Customer" and "order_events" becomes "OrderEvent".
func entityTypeName(tableName string, table Table) string {
	if table.TypeName != "" {
		return table.TypeName
	}
	words := splitIdentifier(tableName)
	if len(words) > 0 {
		words[len(words)-1] = singularise(words[len(words)-1])
	}
	return pascalCaseWords(words)
}

// Irregular English plurals, and a few uncountables the rules below would mangle,
// mapped to their singular form.
var irregularSingulars = map[string]string{
	"people": "person", "men": "man", "women": "woman", "children": "child",
	"teeth": "tooth", "feet": "foot", "mice": "mouse", "geese": "goose",
	// Uncountable / already-singular words ending in -s or -ies.
	"series": "series", "species": "species", "status": "status",
}

// Converts a lowercase plural word to its singular form using common English
// rules. It is deliberately simple, since irregular cases are covered by the
// per-table `typeName` override.
func singularise(word string) string {
	if s, ok := irregularSingulars[word]; ok {
		return s
	}
	switch {
	case len(word) > 3 && strings.HasSuffix(word, "ies"):
		return word[:len(word)-3] + "y"
	case strings.HasSuffix(word, "ses"), strings.HasSuffix(word, "xes"),
		strings.HasSuffix(word, "zes"), strings.HasSuffix(word, "ches"),
		strings.HasSuffix(word, "shes"):
		return word[:len(word)-2]
	case strings.HasSuffix(word, "s") &&
		!strings.HasSuffix(word, "ss") &&
		!strings.HasSuffix(word, "us") &&
		!strings.HasSuffix(word, "is"):
		return word[:len(word)-1]
	default:
		return word
	}
}

// pascalCase converts an identifier (snake_case, kebab-case or camelCase) to
// PascalCase: "order_events" → "OrderEvents", "ordersDb" → "OrdersDb".
func pascalCase(s string) string {
	return pascalCaseWords(splitIdentifier(s))
}

func pascalCaseWords(words []string) string {
	var b strings.Builder
	for _, word := range words {
		if word == "" {
			continue
		}
		b.WriteString(strings.ToUpper(word[:1]))
		b.WriteString(strings.ToLower(word[1:]))
	}
	return b.String()
}

func kebabCase(s string) string {
	return strings.Join(splitIdentifier(s), "-")
}

func snakeCase(s string) string {
	return strings.Join(splitIdentifier(s), "_")
}

// Breaks an identifier into lowercase words on camelCase boundaries and
// non-alphanumeric separators.
func splitIdentifier(s string) []string {
	var words []string
	var cur strings.Builder
	var prev rune
	for i, r := range s {
		isSep := !isAlphaNum(r)
		if isSep {
			if cur.Len() > 0 {
				words = append(words, strings.ToLower(cur.String()))
				cur.Reset()
			}
			prev = r
			continue
		}
		// Split on a lower→upper or letter→digit-group boundary.
		if i > 0 && cur.Len() > 0 && isUpper(r) && !isUpper(prev) {
			words = append(words, strings.ToLower(cur.String()))
			cur.Reset()
		}
		cur.WriteRune(r)
		prev = r
	}
	if cur.Len() > 0 {
		words = append(words, strings.ToLower(cur.String()))
	}
	return words
}

func isAlphaNum(r rune) bool {
	return isUpper(r) || (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9')
}

func isUpper(r rune) bool {
	return r >= 'A' && r <= 'Z'
}
